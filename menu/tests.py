"""Tests for the menu app: models, views, category filtering and contact form.

Run with: python manage.py test
"""

from django.test import TestCase
from django.urls import reverse

from .models import Category, MenuItem, ContactMessage


# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------

class CategoryModelTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.category = Category.objects.create(
            name='Coffees', description='Specialty coffees.'
        )

    def test_slug_autogenerated(self):
        self.assertEqual(self.category.slug, 'coffees')

    def test_str_returns_name(self):
        self.assertEqual(str(self.category), 'Coffees')

    def test_ordering_by_name(self):
        Category.objects.create(name='Breakfast')
        names = list(Category.objects.values_list('name', flat=True))
        self.assertEqual(names, ['Breakfast', 'Coffees'])


