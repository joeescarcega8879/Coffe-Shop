class ContactViewTests(TestCase):
    def test_get_renders_template(self):
        response = self.client.get(reverse('menu:contact'))
        self.assertEqual(response.status_code, 200)
        self.assertTemplateUsed(response, 'menu/contact.html')

    def test_post_valid_creates_message_and_redirects(self):
        response = self.client.post(reverse('menu:contact'), {
            'name': 'Ana',
            'email': 'ana@example.com',
            'phone': '555-1234',
            'message': 'Hello coffee shop!',
        })
        self.assertRedirects(response, reverse('menu:contact'))
        self.assertEqual(ContactMessage.objects.count(), 1)
        msg = ContactMessage.objects.first()
        self.assertEqual(msg.name, 'Ana')
        self.assertEqual(msg.email, 'ana@example.com')
        self.assertEqual(msg.phone, '555-1234')
        self.assertEqual(msg.message, 'Hello coffee shop!')

    def test_post_valid_shows_success_message(self):
        self.client.post(reverse('menu:contact'), {
            'name': 'Ana', 'email': 'ana@example.com', 'message': 'Hello!',
        })
        response = self.client.get(reverse('menu:contact'))
        self.assertContains(response, 'Thank you for your message!')

    def test_post_missing_fields_does_not_save(self):
        response = self.client.post(reverse('menu:contact'), {
            'name': '', 'email': '', 'message': '',
        })
        self.assertEqual(ContactMessage.objects.count(), 0)
        messages = list(response.context['messages'])
        self.assertTrue(any(m.tags == 'error' for m in messages))

    def test_post_phone_optional(self):
        response = self.client.post(reverse('menu:contact'), {
            'name': 'Luis', 'email': 'luis@example.com', 'phone': '', 'message': 'Hi!',
        })
        self.assertRedirects(response, reverse('menu:contact'))
        self.assertEqual(ContactMessage.objects.first().phone, '')
