class MenuDetailViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.category = Category.objects.create(name='Coffees', slug='coffees')
        cls.item = MenuItem.objects.create(
            name='Espresso', description='Concentrated shot.',
            price='3.50', category=cls.category, is_available=True,
        )
        cls.hidden = MenuItem.objects.create(
            name='Secret Item', price='1.00', category=cls.category, is_available=False,
        )

    def test_detail_renders_template_and_data(self):
        response = self.client.get(reverse('menu:menu_detail', args=[self.item.pk]))
