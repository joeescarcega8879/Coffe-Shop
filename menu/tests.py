class MenuListViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.coffees = Category.objects.create(name='Coffees', slug='coffees')
        cls.desserts = Category.objects.create(name='Desserts', slug='desserts')
        cls.espresso = MenuItem.objects.create(
            name='Espresso', price='3.50', category=cls.coffees, is_available=True,
        )
        cls.cheesecake = MenuItem.objects.create(
            name='Cheesecake', price='6.00', category=cls.desserts, is_available=True,
        )
        cls.hidden = MenuItem.objects.create(
            name='Secret Item', price='1.00', category=cls.coffees, is_available=False,
        )

    def test_list_renders_template_and_items(self):
        response = self.client.get(reverse('menu:menu_list'))
        self.assertEqual(response.status_code, 200)
        self.assertTemplateUsed(response, 'menu/menu_list.html')
        self.assertContains(response, 'Espresso')
        self.assertContains(response, 'Cheesecake')
        self.assertNotContains(response, 'Secret Item')

    def test_filter_by_category_slug(self):
        response = self.client.get(reverse('menu:menu_list'), {'categoria': 'coffees'})
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, 'Espresso')
        self.assertNotContains(response, 'Cheesecake')
        self.assertEqual(response.context['active_category'], 'coffees')

    def test_filter_invalid_slug_returns_empty(self):
        response = self.client.get(reverse('menu:menu_list'), {'categoria': 'no-existe'})
        self.assertEqual(response.status_code, 200)
        self.assertEqual(len(response.context['items']), 0)


